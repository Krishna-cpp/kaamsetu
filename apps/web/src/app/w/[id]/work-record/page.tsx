import { getCtx, getWorkRecord, isOwner, skillLabel } from '@kaamsetu/core/server';
import { Check, Info, Lock, Minus } from 'lucide-react';
import type { Metadata } from 'next';
import Link from 'next/link';
import { notFound } from 'next/navigation';
import { BOCW_DAYS } from '@/components/benefits/days-bar';
import { PrintButton } from '@/components/benefits/print-button';

export const dynamic = 'force-dynamic';

type Props = { params: Promise<{ id: string }>; searchParams: Promise<Record<string, string | string[] | undefined>> };

const META: Metadata = {
  title: 'Work record',
  robots: { index: false, follow: false, nocache: true },
};

export async function generateMetadata(): Promise<Metadata> {
  return META;
}

const idNumber = (id: string) => 'KS-' + id.replace(/^w_/, '').toUpperCase();
const day = (iso: string) =>
  new Date(iso.length === 10 ? iso + 'T00:00:00Z' : iso).toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    timeZone: 'Asia/Kolkata',
  });
const stamp = (iso: string) =>
  new Date(iso).toLocaleString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    timeZone: 'Asia/Kolkata',
  });

export default async function WorkRecordPage({ params, searchParams }: Props) {
  const ctx = getCtx();
  if (!ctx.env.FEATURE_SCHEMES) notFound();
  const id = (await params).id;
  const k = (await searchParams).k;
  // no valid private-link token: say nothing about the worker, not even whether they exist
  if (!isOwner(ctx, id, typeof k === 'string' ? k : null)) return <PrivateRecord />;

  const rec = await getWorkRecord(ctx, id);
  if (!rec) notFound();
  const { worker: w, rows } = rec;
  const total = rec.constructionDays12m;
  const confirmed = rows.filter((r) => r.confirmed).length;
  const reached = total >= BOCW_DAYS;

  return (
    <div className="ks-record min-h-dvh pt-14">
      <div className="container-x max-w-[960px] py-8 sm:py-12">
        {/* disclaimer first: this is a supporting record, not a certificate */}
        <div className="ks-record-note flex items-start gap-3 border-2 border-ink bg-signal p-3.5 sm:p-4" role="note">
          <Info className="mt-0.5 size-4 shrink-0" aria-hidden />
          <p className="text-[14px] font-medium leading-snug">
            Work record generated by KaamSetu to support a welfare board application. Not an official certificate. The board may require its
            own employer certificate format.
          </p>
        </div>

        <div className="mt-8 grid grid-cols-1 gap-6 border-b-2 border-ink pb-6 sm:grid-cols-[minmax(0,1fr)_auto] sm:items-end">
          <div className="min-w-0">
            <p className="label text-concrete-dark">KaamSetu · Work record · {idNumber(w.id)}</p>
            <h1 className="display mt-3 text-[44px] sm:text-[64px]">{w.name}</h1>
            <p className="mt-3 font-display text-xl font-semibold tracking-tight">
              {w.skills.map((s) => skillLabel(s)).join(' · ')}
              <span className="serif-i font-normal text-concrete-dark"> in {w.locality}</span>
            </p>
          </div>
          <PrintButton />
        </div>

        <dl className="grid grid-cols-2 border-b border-line sm:grid-cols-4">
          {[
            { k: 'Worker ID', v: idNumber(w.id) },
            { k: 'Trade', v: w.skills.map((s) => skillLabel(s)).join(', ') },
            { k: 'Locality', v: w.locality },
            { k: 'Generated', v: stamp(rec.generatedAt) },
          ].map((f, i) => (
            <div
              key={f.k}
              className={`border-line py-3 pr-2 ${i % 2 ? 'border-l pl-3' : ''} sm:pl-3 sm:first:pl-0 ${i > 0 ? 'sm:border-l' : ''} ${i > 1 ? 'max-sm:border-t' : ''}`}
            >
              <dt className="label text-[10px] text-concrete">{f.k}</dt>
              <dd className="mt-1 text-[15px] font-medium leading-tight">{f.v}</dd>
            </div>
          ))}
        </dl>

        {/* total */}
        <div className="ks-record-total mt-6 flex flex-wrap items-end justify-between gap-4 border-2 border-ink p-4 sm:p-5">
          <div>
            <p className="label text-concrete-dark">Construction days · last 12 months</p>
            <p className="mt-2 flex items-baseline gap-2">
              <span className="display text-[64px] tabular-nums">{total}</span>
              <span className="font-display text-xl font-semibold text-concrete-dark">days</span>
            </p>
          </div>
          <div className="text-[14px] leading-snug sm:text-right">
            <p>
              <span className="font-mono">{rows.length}</span> completed job{rows.length === 1 ? '' : 's'} ·{' '}
              <span className="font-mono">{confirmed}</span> employer-confirmed
            </p>
            <p className="mt-1 text-concrete-dark">
              {reached ? `At or above the ${BOCW_DAYS}-day mark boards ask for.` : `${BOCW_DAYS - total} more days to reach ${BOCW_DAYS}.`}
            </p>
          </div>
        </div>

        {/* rows */}
        <h2 className="label mt-10 flex items-center justify-between border-b border-ink pb-2">
          Jobs completed through KaamSetu <span className="text-concrete">Newest first</span>
        </h2>
        {rows.length === 0 ? (
          <p className="py-6 text-sm text-concrete-dark">No completed jobs yet. Jobs show up here after the employer marks them done.</p>
        ) : (
          <>
            {/* phones: stacked rows (screen only) */}
            <ol className="divide-y divide-line sm:hidden print:hidden">
              {rows.map((r) => (
                <li key={r.matchId} className="grid grid-cols-[minmax(0,1fr)_auto] gap-x-3 gap-y-0.5 py-3">
                  <p className="font-medium">
                    {r.tradeLabel} · {r.locality}
                  </p>
                  <p className="font-mono text-sm">
                    {r.days} day{r.days === 1 ? '' : 's'}
                  </p>
                  <p className="text-[13px] text-concrete-dark">
                    {day(r.date)} · {r.employer}
                  </p>
                  <p className="label text-right text-[10px]">
                    {r.confirmed ? <span className="text-ok">Confirmed</span> : <span className="text-concrete">Unconfirmed</span>}
                  </p>
                  {!r.construction && <p className="col-span-2 text-xs text-concrete">Not construction work: not counted</p>}
                </li>
              ))}
            </ol>
            <table className="ks-record-table hidden w-full border-collapse text-left text-[14px] sm:table print:table">
              <caption className="sr-only">
                Completed jobs: date, days, trade, location, employer and whether the employer confirmed
              </caption>
              <thead>
                <tr className="label border-b border-ink text-[10px] text-concrete-dark">
                  <th scope="col" className="py-2 pr-3 font-normal">
                    Date
                  </th>
                  <th scope="col" className="py-2 pr-3 text-right font-normal">
                    Days
                  </th>
                  <th scope="col" className="py-2 pr-3 font-normal">
                    Trade
                  </th>
                  <th scope="col" className="py-2 pr-3 font-normal">
                    Location
                  </th>
                  <th scope="col" className="py-2 pr-3 font-normal">
                    Employer
                  </th>
                  <th scope="col" className="py-2 text-center font-normal">
                    Confirmed
                  </th>
                </tr>
              </thead>
              <tbody>
                {rows.map((r) => (
                  <tr key={r.matchId} className="border-b border-line align-top">
                    <td className="whitespace-nowrap py-2.5 pr-3 font-mono text-[13px]">{day(r.date)}</td>
                    <td className="py-2.5 pr-3 text-right font-mono">{r.days}</td>
                    <td className="py-2.5 pr-3">
                      {r.tradeLabel}
                      {!r.construction && <span className="block text-xs text-concrete">not counted</span>}
                    </td>
                    <td className="py-2.5 pr-3">{r.locality}</td>
                    <td className="py-2.5 pr-3">{r.employer}</td>
                    <td className="py-2.5 text-center">
                      {r.confirmed ? (
                        <Check className="mx-auto size-4 text-ok" strokeWidth={3} aria-label="Confirmed by employer" />
                      ) : (
                        <Minus className="mx-auto size-4 text-concrete" aria-label="Not confirmed" />
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
              <tfoot>
                <tr className="border-t-2 border-ink">
                  <th scope="row" className="py-2.5 pr-3 text-left font-semibold">
                    Last 12 months
                  </th>
                  <td className="py-2.5 pr-3 text-right font-mono font-semibold">{total}</td>
                  <td colSpan={4} className="py-2.5 text-[13px] text-concrete-dark">
                    construction days (completed jobs only)
                  </td>
                </tr>
              </tfoot>
            </table>
          </>
        )}

        <div className="mt-8 grid grid-cols-1 gap-6 border-t border-line pt-5 text-[12.5px] leading-relaxed text-concrete-dark sm:grid-cols-2">
          <p>
            <span className="font-semibold text-ink">How days are counted.</span> Each job adds the days the employer booked, once the
            employer marks it done. Only construction trades count toward the welfare-board total. &ldquo;Confirmed&rdquo; means the
            employer confirmed on KaamSetu that this worker did the job.
          </p>
          <p>
            <span className="font-semibold text-ink">Privacy.</span> Phone numbers and exact addresses are never shown on this record. This
            page is private to {w.name.split(' ')[0]}; anyone with the link can see it, so share it only with the board or a help centre.
          </p>
        </div>
        <p className="no-print mt-6">
          <Link href={`/w/${w.id}`} className="label text-concrete-dark underline underline-offset-4 hover:text-ink">
            Back to public ID card
          </Link>
        </p>
      </div>
    </div>
  );
}

function PrivateRecord() {
  return (
    <div className="grid min-h-dvh place-items-center px-4 pt-14">
      <div className="w-full max-w-[520px] border-2 border-ink bg-[#FBF8F1] shadow-[6px_6px_0_0_#121210]">
        <div className="hazard h-3 border-b-2 border-ink" aria-hidden />
        <div className="p-6 sm:p-8">
          <span className="grid size-12 place-items-center bg-ink text-signal" aria-hidden>
            <Lock className="size-5" />
          </span>
          <p className="label mt-6 text-concrete-dark">Work record</p>
          <h1 className="display mt-2 text-[40px] sm:text-[52px]">
            This record is <span className="serif-i font-normal text-hivis">private.</span>
          </h1>
          <p className="mt-4 text-[15px] leading-relaxed text-ink/80">
            Only the worker can open it, from the private link the KaamSetu bot sends. If this is your record, ask the bot &ldquo;work
            record&rdquo; and tap the link it sends you.
          </p>
          <Link href="/" className="label mt-6 inline-flex h-11 items-center bg-ink px-4 text-paper hover:bg-hivis hover:text-ink">
            Go to KaamSetu
          </Link>
        </div>
      </div>
    </div>
  );
}
